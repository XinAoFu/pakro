const INSTALLER: &[u8] = b"pakro\n";

pub(crate) struct WheelInstallTarget<'a> {
    pub scheme: &'a WheelInstallScheme,
    pub interpreter: &'a Path,
    pub reserved: &'a [WheelReservedDestination],
}

#[derive(Debug, Clone, Copy)]
pub(crate) struct WheelInstallLimits {
    pub scripts: WheelScriptLimits,
    pub max_record_rows: usize,
    pub max_record_bytes: usize,
    pub max_generated_bytes: u64,
}

impl Default for WheelInstallLimits {
    fn default() -> Self {
        Self {
            scripts: WheelScriptLimits::default(),
            max_record_rows: 1_048_576,
            max_record_bytes: 64 * 1024 * 1024,
            max_generated_bytes: 512 * 1024 * 1024,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct PreparedWheelSource {
    owner: WheelOwner,
    filename: String,
    digest: Digest,
    size: u64,
}

impl PreparedWheelSource {
    pub(crate) fn owner(&self) -> &WheelOwner {
        &self.owner
    }
    pub(crate) fn filename(&self) -> &str {
        &self.filename
    }
    pub(crate) fn digest(&self) -> Digest {
        self.digest
    }
    pub(crate) fn size(&self) -> u64 {
        self.size
    }
}

#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
enum OutputKey {
    Archive {
        owner: WheelOwner,
        archive_index: usize,
    },
    Generated {
        owner: WheelOwner,
        target: WheelGeneratedTarget,
    },
}

enum PreparedBytes {
    Memory(Vec<u8>),
    Spool(File),
}

struct PreparedOutput {
    bytes: PreparedBytes,
    sha256: [u8; 32],
    size: u64,
    mode: u32,
    operation: WheelWriteOperation,
}

impl fmt::Debug for PreparedOutput {
    fn fmt(&self, output: &mut fmt::Formatter<'_>) -> fmt::Result {
        output
            .debug_struct("PreparedOutput")
            .field("sha256", &self.sha256)
            .field("size", &self.size)
            .field("mode", &self.mode)
            .field("operation", &self.operation)
            .finish_non_exhaustive()
    }
}

pub(crate) struct PreparedWheelGraph {
    archives: BTreeMap<WheelOwner, InspectedWheelArchive>,
    outputs: BTreeMap<OutputKey, PreparedOutput>,
    complete: CompleteWheelGraphPlan,
    sources: Vec<PreparedWheelSource>,
}

impl PreparedWheelGraph {
    pub(crate) fn plan(&self) -> &WheelGraphPlan {
        self.complete.plan()
    }
    pub(crate) fn sources(&self) -> &[PreparedWheelSource] {
        &self.sources
    }
}

impl fmt::Debug for PreparedWheelGraph {
    fn fmt(&self, output: &mut fmt::Formatter<'_>) -> fmt::Result {
        output
            .debug_struct("PreparedWheelGraph")
            .field("source_count", &self.archives.len())
            .field("output_count", &self.outputs.len())
            .field("file_count", &self.plan().files().len())
            .finish_non_exhaustive()
    }
}

pub(crate) fn prepare_wheel_graph(
    archives: Vec<InspectedWheelArchive>,
    target: &WheelInstallTarget<'_>,
    wheel_limits: WheelLimits,
    plan_limits: WheelPlanLimits,
    install_limits: WheelInstallLimits,
    scratch_root: &Path,
) -> Result<PreparedWheelGraph> {
    prepare::prepare(
        archives,
        target,
        wheel_limits,
        plan_limits,
        install_limits,
        scratch_root,
    )
}

// This separately testable final gate binds B's complete facts to C's actual
// owned sources and generated bytes. It is not a public plan constructor.
fn validate_prepared_bindings(prepared: &mut PreparedWheelGraph) -> Result<()> {
    bindings::validate(prepared)
}

