//! Private prepared-output bytes and checked aggregate accounting.

use std::io::{Read, Seek};

use eyre::{Result, ensure, eyre};
use sha2::{Digest as _, Sha256};

use super::{PreparedBytes, PreparedOutput, WheelWriteOperation};

impl PreparedOutput {
    pub(super) fn memory(bytes: Vec<u8>, mode: u32, operation: WheelWriteOperation) -> Self {
        Self {
            sha256: Sha256::digest(&bytes).into(),
            size: bytes.len() as u64,
            bytes: PreparedBytes::Memory(bytes),
            mode,
            operation,
        }
    }

    pub(super) fn check_bytes(&mut self) -> Result<()> {
        let (size, sha256): (u64, [u8; 32]) = match &mut self.bytes {
            PreparedBytes::Memory(bytes) => (bytes.len() as u64, Sha256::digest(bytes).into()),
            PreparedBytes::Spool(file) => {
                file.rewind()
                    .map_err(|_| eyre!("wheel output spool seek failed"))?;
                let mut hasher = Sha256::new();
                let mut size = 0_u64;
                let mut buffer = [0; 64 * 1024];
                loop {
                    let count = file
                        .read(&mut buffer)
                        .map_err(|_| eyre!("wheel output spool read failed"))?;
                    if count == 0 {
                        break;
                    }
                    size = size
                        .checked_add(count as u64)
                        .ok_or_else(|| eyre!("wheel output byte limit overflow"))?;
                    ensure!(
                        size <= self.size,
                        "wheel output size disagrees with prepared facts"
                    );
                    hasher.update(&buffer[..count]);
                }
                (size, hasher.finalize().into())
            }
        };
        ensure!(
            size == self.size && sha256 == self.sha256,
            "wheel output bytes disagree with prepared facts"
        );
        Ok(())
    }
}

pub(super) struct GeneratedBudget {
    used: u64,
    maximum: u64,
}
impl GeneratedBudget {
    pub(super) fn new(maximum: u64) -> Self {
        Self { used: 0, maximum }
    }
    pub(super) fn remaining(&self) -> u64 {
        self.maximum - self.used
    }
    pub(super) fn reserve(&mut self, bytes: u64) -> Result<()> {
        let used = self
            .used
            .checked_add(bytes)
            .ok_or_else(|| eyre!("wheel generated byte limit overflow"))?;
        ensure!(used <= self.maximum, "wheel generated byte limit exceeded");
        self.used = used;
        Ok(())
    }
}
