#!/usr/bin/env bash
set -euxo pipefail

# Release URLs are supplied by the pakro publisher; an unconfigured local render
# leaves the installer requiring an explicit download source at runtime.
PAKRO_DEFAULT_DOWNLOAD_BASE_URL="${PAKRO_DOWNLOAD_BASE_URL:-}"
PAKRO_DEFAULT_RELEASE_REPOSITORY="${PAKRO_RELEASE_REPOSITORY:-${GITHUB_REPOSITORY:-}}"
if [[ "$PAKRO_DEFAULT_RELEASE_REPOSITORY" == "jdx/mise" ]]; then PAKRO_DEFAULT_RELEASE_REPOSITORY=""; fi
pakro_url_pattern='^https?://[A-Za-z0-9._~:/?#@!%&=+,;-]+$'
if [[ -n "$PAKRO_DEFAULT_DOWNLOAD_BASE_URL" && ! "$PAKRO_DEFAULT_DOWNLOAD_BASE_URL" =~ $pakro_url_pattern ]] ||
   [[ -n "$PAKRO_DEFAULT_RELEASE_REPOSITORY" && ! "$PAKRO_DEFAULT_RELEASE_REPOSITORY" =~ ^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$ ]]; then
  echo "Invalid pakro release source" >&2
  exit 1
fi
export PAKRO_DEFAULT_DOWNLOAD_BASE_URL PAKRO_DEFAULT_RELEASE_REPOSITORY

# shellcheck disable=SC2016
PAKRO_CURRENT_VERSION=$PAKRO_VERSION \
	PAKRO_CHECKSUM_LINUX_X86_64=$(grep "pakro-v.*linux-x64.tar.gz" "$RELEASE_DIR/$PAKRO_VERSION/SHASUMS256.txt") \
	PAKRO_CHECKSUM_LINUX_X86_64_MUSL=$(grep "pakro-v.*linux-x64-musl.tar.gz" "$RELEASE_DIR/$PAKRO_VERSION/SHASUMS256.txt") \
	PAKRO_CHECKSUM_LINUX_ARM64=$(grep "pakro-v.*linux-arm64.tar.gz" "$RELEASE_DIR/$PAKRO_VERSION/SHASUMS256.txt") \
	PAKRO_CHECKSUM_LINUX_ARM64_MUSL=$(grep "pakro-v.*linux-arm64-musl.tar.gz" "$RELEASE_DIR/$PAKRO_VERSION/SHASUMS256.txt") \
	PAKRO_CHECKSUM_LINUX_ARMV7=$(grep "pakro-v.*linux-armv7.tar.gz" "$RELEASE_DIR/$PAKRO_VERSION/SHASUMS256.txt") \
	PAKRO_CHECKSUM_LINUX_ARMV7_MUSL=$(grep "pakro-v.*linux-armv7-musl.tar.gz" "$RELEASE_DIR/$PAKRO_VERSION/SHASUMS256.txt") \
	PAKRO_CHECKSUM_MACOS_X86_64=$(grep "pakro-v.*macos-x64.tar.gz" "$RELEASE_DIR/$PAKRO_VERSION/SHASUMS256.txt") \
	PAKRO_CHECKSUM_MACOS_ARM64=$(grep "pakro-v.*macos-arm64.tar.gz" "$RELEASE_DIR/$PAKRO_VERSION/SHASUMS256.txt") \
	PAKRO_CHECKSUM_LINUX_X86_64_ZSTD=$(grep "pakro-v.*linux-x64.tar.zst" "$RELEASE_DIR/$PAKRO_VERSION/SHASUMS256.txt") \
	PAKRO_CHECKSUM_LINUX_X86_64_MUSL_ZSTD=$(grep "pakro-v.*linux-x64-musl.tar.zst" "$RELEASE_DIR/$PAKRO_VERSION/SHASUMS256.txt") \
	PAKRO_CHECKSUM_LINUX_ARM64_ZSTD=$(grep "pakro-v.*linux-arm64.tar.zst" "$RELEASE_DIR/$PAKRO_VERSION/SHASUMS256.txt") \
	PAKRO_CHECKSUM_LINUX_ARM64_MUSL_ZSTD=$(grep "pakro-v.*linux-arm64-musl.tar.zst" "$RELEASE_DIR/$PAKRO_VERSION/SHASUMS256.txt") \
	PAKRO_CHECKSUM_LINUX_ARMV7_ZSTD=$(grep "pakro-v.*linux-armv7.tar.zst" "$RELEASE_DIR/$PAKRO_VERSION/SHASUMS256.txt") \
	PAKRO_CHECKSUM_LINUX_ARMV7_MUSL_ZSTD=$(grep "pakro-v.*linux-armv7-musl.tar.zst" "$RELEASE_DIR/$PAKRO_VERSION/SHASUMS256.txt") \
	PAKRO_CHECKSUM_MACOS_X86_64_ZSTD=$(grep "pakro-v.*macos-x64.tar.zst" "$RELEASE_DIR/$PAKRO_VERSION/SHASUMS256.txt") \
	PAKRO_CHECKSUM_MACOS_ARM64_ZSTD=$(grep "pakro-v.*macos-arm64.tar.zst" "$RELEASE_DIR/$PAKRO_VERSION/SHASUMS256.txt") \
	envsubst '$PAKRO_DEFAULT_DOWNLOAD_BASE_URL,$PAKRO_DEFAULT_RELEASE_REPOSITORY,$PAKRO_CURRENT_VERSION,$PAKRO_CHECKSUM_LINUX_X86_64,$PAKRO_CHECKSUM_LINUX_X86_64_MUSL,$PAKRO_CHECKSUM_LINUX_ARM64,$PAKRO_CHECKSUM_LINUX_ARM64_MUSL,$PAKRO_CHECKSUM_LINUX_ARMV6,$PAKRO_CHECKSUM_LINUX_ARMV6_MUSL,$PAKRO_CHECKSUM_LINUX_ARMV7,$PAKRO_CHECKSUM_LINUX_ARMV7_MUSL,$PAKRO_CHECKSUM_MACOS_X86_64,$PAKRO_CHECKSUM_MACOS_ARM64,$PAKRO_CHECKSUM_LINUX_X86_64_ZSTD,$PAKRO_CHECKSUM_LINUX_X86_64_MUSL_ZSTD,$PAKRO_CHECKSUM_LINUX_ARM64_ZSTD,$PAKRO_CHECKSUM_LINUX_ARM64_MUSL_ZSTD,$PAKRO_CHECKSUM_LINUX_ARMV7_ZSTD,$PAKRO_CHECKSUM_LINUX_ARMV7_MUSL_ZSTD,$PAKRO_CHECKSUM_MACOS_X86_64_ZSTD,$PAKRO_CHECKSUM_MACOS_ARM64_ZSTD' \
	<"$BASE_DIR/packaging/standalone/install.envsubst"
